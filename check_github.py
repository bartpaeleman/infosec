def check_link(url):
    try:
        req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/91.0.4472.124 Safari/537.36'})
        urllib.request.urlopen(req, timeout=10)
        return (url, True)
    except urllib.error.HTTPError as e:
        if e.code == 404:
            # specifically for GitHub, 404 might mean private or deleted
            return (url, False)
        return (url, True) # Other errors like 403 we can ignore
    except Exception as e:
        return (url, False)

with concurrent.futures.ThreadPoolExecutor(max_workers=20) as executor:
    results = executor.map(check_link, set(broken_list))

actually_broken = []
for url, is_valid in results:
    if not is_valid:
        actually_broken.append(url)
        print(f"Dead Link: {url}")
